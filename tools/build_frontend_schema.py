"""Generate frontend/aed-schema.js from schema/aed.schema.json and schema/aed-example.csv.

Browsers block fetch() from file:// pages, so the in-browser demo gets the schema as a script
(window.AED_SCHEMA) and the example records as window.AED_EXAMPLES. Run after editing the schema:

    python tools/build_frontend_schema.py

tests/test_schema_files.py fails if the generated file is out of date.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema" / "aed.schema.json"
EXAMPLES = ROOT / "schema" / "aed-example.csv"
OUTPUT = ROOT / "frontend" / "aed-schema.js"

HEADER = "// GENERATED by tools/build_frontend_schema.py from schema/ — do not edit by hand.\n"


def render():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    with open(str(EXAMPLES), encoding="utf-8", newline="") as fh:
        examples = list(csv.DictReader(fh))
    return (
        HEADER
        + "window.AED_SCHEMA = "
        + json.dumps(schema, ensure_ascii=False, indent=1)
        + ";\nwindow.AED_EXAMPLES = "
        + json.dumps(examples, ensure_ascii=False, indent=1)
        + ";\n"
    )


def main():
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Written {OUTPUT}")


if __name__ == "__main__":
    main()
